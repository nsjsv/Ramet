import { localStamp } from '../../../triggers/schedule.js'

/** 每一轮输入最前面的一行：当前时间与用户的时区。Genet 要靠它理解「明天 9 点」「下周一」，才能设对定时器；
 *  进会话历史，读旧消息时也知道当时是几点 */
export function clockLine(now: Date, tz: string): string {
  return `[现在：${localStamp(now, tz)}（${tz}）]`
}

